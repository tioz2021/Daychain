#!/bin/sh
# Embed web/ assets into a C source file.
# Usage: tools/embed_web.sh <out.c> <file> [file...]
set -eu

out=$1
shift

mime_of() {
    case "$1" in
        *.html) echo "text/html; charset=utf-8" ;;
        *.css)  echo "text/css; charset=utf-8" ;;
        *.js)   echo "text/javascript; charset=utf-8" ;;
        *.json) echo "application/json; charset=utf-8" ;;
        *.svg)  echo "image/svg+xml" ;;
        *.png)  echo "image/png" ;;
        *.ico)  echo "image/x-icon" ;;
        *.woff2) echo "font/woff2" ;;
        *)      echo "application/octet-stream" ;;
    esac
}

# Map a source path (relative, absolute or ./prefixed) to its URL path.
rel_of() {
    case "$1" in
        */web/*) printf '%s' "${1#*/web/}" ;;
        web/*)   printf '%s' "${1#web/}" ;;
        ./*)     printf '%s' "${1#./}" ;;
        *)       basename -- "$1" ;;
    esac
}

mkdir -p "$(dirname "$out")"

{
    echo '/* Generated by tools/embed_web.sh - do not edit. */'
    echo '#include "infra/web.h"'
    echo

    n=0
    for f in "$@"; do
        printf 'static const unsigned char a%d[] = {' "$n"
        bytes=$(od -An -v -tu1 "$f" | tr -s ' \n' ' ' | sed 's/^ //; s/ $//; s/ /,/g')
        if [ -z "$bytes" ]; then bytes=0; fi
        printf '%s};\n' "$bytes"
        n=$((n + 1))
    done

    echo
    echo 'const WebAsset web_assets[] = {'
    n=0
    for f in "$@"; do
        rel=$(rel_of "$f")
        case "$rel" in
            /*|*..*)
                echo "embed_web.sh: refusing suspicious asset path: $f" >&2
                exit 1
                ;;
        esac
        printf '    {"/%s", "%s", a%d, sizeof a%d},\n' "$rel" "$(mime_of "$f")" "$n" "$n"
        n=$((n + 1))
    done
    echo '};'
    echo
    echo 'const unsigned web_assets_count = sizeof(web_assets) / sizeof(web_assets[0]);'
} > "$out"
